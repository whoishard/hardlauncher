export function getLanguage() {
  return useAppStore.getState().settings?.language || 'es';
}

export function dateLocale(lang = getLanguage()) {
  if (lang === 'pt') return 'pt-BR';
  if (lang === 'en') return 'en-US';
  return 'es';
}

export function t(key, vars, lang = getLanguage()) {
  const dict = translations[lang] || translations.es;
  const str = dict[key] ?? translations.es[key] ?? key;
  return interpolate(str, vars);
}

export function useT() {
  const language = useAppStore((s) => s.settings?.language) || 'es';
  return useMemo(() => {
    const fn = (key, vars) => t(key, vars, language);
    fn.lang = language;
    fn.dateLocale = dateLocale(language);
    return fn;
  }, [language]);
}

/**
 * Antes esto se quedaba corto para jugadores con muchas horas encima: pasado
 * el día de juego acumulado seguía mostrando todo apilado en horas ("31h
 * 40m"), sin desglosar en días — que es lo que de verdad importa mirar de
 * un vistazo cuando el total ya es grande. Ahora, pasadas las 24h
 * acumuladas, se desglosa también en días ("1d 7h 40m"), quedando el
 * mismo "Xh Ym" de siempre para los totales más chicos.
 */
export function formatPlaytimeShort(ms, lang = getLanguage()) {
  const totalMinutes = Math.floor((ms || 0) / 60000);
  const days = Math.floor(totalMinutes / 1440);
  const hours = Math.floor((totalMinutes % 1440) / 60);
  const minutes = totalMinutes % 60;
  if (days > 0) return `${days}d ${hours}h ${minutes}m`;
  if (hours === 0) return `${minutes}m`;
  return `${hours}h ${minutes}m`;
}

export function formatPlaytimePlayed(ms, lang = getLanguage()) {
  const totalMinutes = Math.floor((ms || 0) / 60000);
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  if (hours === 0) return t('instances.playedMinutes', { n: minutes }, lang);
  return t('instances.playedHours', { h: hours, m: minutes }, lang);
}

export function formatRelativeDate(dateStr, lang = getLanguage()) {
  const d = new Date(dateStr);
  const now = Date.now();
  const diffDay = Math.floor((now - d.getTime()) / 86400000);
  if (diffDay < 7) return t('rel.days', { n: Math.max(diffDay, 0) }, lang);
  if (diffDay < 30) return t('rel.weeks', { n: Math.floor(diffDay / 7) }, lang);
  const diffMonth = Math.floor(diffDay / 30);
  if (diffMonth === 1) return t('rel.lastMonth', null, lang);
  if (diffMonth < 12) return t('rel.months', { n: diffMonth }, lang);
  const diffYear = Math.floor(diffDay / 365);
  return diffYear === 1 ? t('rel.lastYear', null, lang) : t('rel.years', { n: diffYear }, lang);
}
